const productMap = new Map(products.map((product) => [product.id, product]));
const legacyMap = new Map(products.map((product) => [product.legacyId, product.id]));

export function getProductById(id) {
    if (!id) return null;

    const normalizedId = String(id);
    const mappedId = legacyMap.get(normalizedId) || normalizedId;

    return productMap.get(mappedId) || null;
}

export function getProductRoute(productId, rootPath = "") {
    return `${rootPath}products/${productId}/`;
}

export function getHomeRoute(rootPath = "") {
    return `${rootPath}index.html`;
}

export function getCartRoute(rootPath = "") {
    return `${rootPath}cart.html`;
}

export function getRelatedProducts(productId) {
    const currentProduct = getProductById(productId);
    if (!currentProduct) return products.slice(0, 4);

    const others = products.filter((product) => product.id !== currentProduct.id);
    return [...others, currentProduct].slice(0, 4);
}

export function formatCurrency(value) {
    return `₹${Number(value).toLocaleString("en-IN")}`;
}

export function resolveAsset(rootPath, assetPath) {
    return `${rootPath}${assetPath}`;
}
